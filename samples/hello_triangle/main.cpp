// hello_triangle: uploads hello_triangle.vusl to VU1 and has it draw one
// triangle with a colour per vertex, every frame.

#include <tamtypes.h>
#include <kernel.h>
#include <dma.h>
#include <draw.h>
#include <draw3d.h>
#include <gif_tags.h>
#include <graph.h>
#include <gs_gp.h>
#include <gs_psm.h>
#include <packet2.h>
#include <packet2_utils.h>

#include <cstddef>

// The program's start and end in the .vsm, declared by the generated header.
#define VUSL_DECLARE_PROGRAM(name)                                       \
    extern "C" u32 name##_CodeStart __attribute__((section(".vudata"))); \
    extern "C" u32 name##_CodeEnd __attribute__((section(".vudata")));

// The program's memory layout, generated by oxide-vusl from hello_triangle.vusl.
#include "hello_triangle.vusl.h"

namespace vu = vusl::HelloTriangle;

constexpr int kWidth  = 640;
constexpr int kHeight = 448;

// The batch as VU1 reads it: Batch's fixed part, then the vertices.
struct alignas(16) TriangleBatch
{
    vu::Batch  head;
    vu::Vertex vertices[3];
};
static_assert(offsetof(TriangleBatch, vertices) == vu::kBatchVertices * 16, "vertices follow the head");
static_assert(vu::kBatchMaxCount >= 3, "VU1 data memory holds the batch and the packet built after it");

static vu::Screen    screen;
static TriangleBatch batch;

static void upload_program()
{
    u32 size = packet2_utils_get_packet_size_for_program(&HelloTriangle_CodeStart, &HelloTriangle_CodeEnd) + 1;
    packet2_t *packet = packet2_create(size, P2_TYPE_NORMAL, P2_MODE_CHAIN, 1);
    packet2_vif_add_micro_program(packet, 0, &HelloTriangle_CodeStart, &HelloTriangle_CodeEnd);
    packet2_utils_vu_add_end_tag(packet);
    dma_channel_send_packet2(packet, DMA_CHANNEL_VIF1, 1);
    dma_channel_wait(DMA_CHANNEL_VIF1, 0);
    packet2_free(packet);
}

static void init_gs(framebuffer_t *frame, zbuffer_t *z)
{
    frame->width   = kWidth;
    frame->height  = kHeight;
    frame->mask    = 0;
    frame->psm     = GS_PSM_32;
    frame->address = graph_vram_allocate(kWidth, kHeight, GS_PSM_32, GRAPH_ALIGN_PAGE);

    z->enable  = DRAW_DISABLE;
    z->mask    = 1;
    z->method  = ZTEST_METHOD_ALLPASS;
    z->zsm     = GS_ZBUF_32;
    z->address = 0;

    graph_initialize(frame->address, kWidth, kHeight, GS_PSM_32, 0, 0);

    packet2_t *packet = packet2_create(20, P2_TYPE_NORMAL, P2_MODE_NORMAL, 0);
    packet2_update(packet, draw_setup_environment(packet->next, 0, frame, z));
    packet2_update(packet, draw_primitive_xyoffset(packet->next, 0, 2048 - kWidth / 2, 2048 - kHeight / 2));
    packet2_update(packet, draw_finish(packet->next));
    dma_channel_send_packet2(packet, DMA_CHANNEL_GIF, 1);
    dma_wait_fast();
    packet2_free(packet);
}

static void clear_screen(packet2_t *packet)
{
    packet2_reset(packet, 0);
    packet2_update(packet, draw_clear(packet->next, 0, 2048 - kWidth / 2, 2048 - kHeight / 2, kWidth, kHeight,
                                      0x20, 0x20, 0x30));
    packet2_update(packet, draw_finish(packet->next));
    dma_channel_send_packet2(packet, DMA_CHANNEL_GIF, 1);
    dma_wait_fast();
    draw_wait_finish();
}

// Sends the screen mapping and the batch to their addresses, then starts the program.
static void draw_triangle(packet2_t *packet)
{
    packet2_reset(packet, 0);
    packet2_utils_vu_add_unpack_data(packet, vu::kScreenAddress, &screen, sizeof(screen) / 16, 0);
    packet2_utils_vu_add_unpack_data(packet, vu::kBatchAddress, &batch, sizeof(batch) / 16, 0);
    packet2_utils_vu_add_start_program(packet, 0);
    packet2_utils_vu_add_end_tag(packet);
    dma_channel_send_packet2(packet, DMA_CHANNEL_VIF1, 1);
    dma_channel_wait(DMA_CHANNEL_VIF1, 0);
}

int main()
{
    dma_channel_initialize(DMA_CHANNEL_GIF, nullptr, 0);
    dma_channel_initialize(DMA_CHANNEL_VIF1, nullptr, 0);
    dma_channel_fast_waits(DMA_CHANNEL_GIF);

    framebuffer_t frame;
    zbuffer_t     z;
    init_gs(&frame, &z);
    upload_program();

    // [-1, 1] to the GS window: the screen's centre is at 2048, 2048.
    screen.scale  = {kWidth / 2, -kHeight / 2, 0.0f, 0.0f};
    screen.offset = {2048.0f, 2048.0f, 0.0f, 0.0f};

    // One Gouraud-shaded triangle: a GIF tag for three RGBAQ + XYZ2 vertices.
    const u64 prim = GS_SET_PRIM(PRIM_TRIANGLE, PRIM_SHADE_GOURAUD, DRAW_DISABLE, DRAW_DISABLE, DRAW_DISABLE,
                                 DRAW_DISABLE, PRIM_MAP_ST, 0, PRIM_UNFIXED);
    batch.head.count     = 3;
    batch.head.tag.dw[0] = GIF_SET_TAG(3, 1, 1, prim, GIF_FLG_PACKED, 2);
    batch.head.tag.dw[1] = DRAW_RGBAQ_REGLIST;
    batch.vertices[0]    = {{255.0f, 0.0f, 0.0f, 128.0f}, {0.0f, 0.8f, 0.0f, 0.0f}};
    batch.vertices[1]    = {{0.0f, 255.0f, 0.0f, 128.0f}, {0.7f, -0.6f, 0.0f, 0.0f}};
    batch.vertices[2]    = {{0.0f, 0.0f, 255.0f, 128.0f}, {-0.7f, -0.6f, 0.0f, 0.0f}};

    packet2_t *gif = packet2_create(80, P2_TYPE_NORMAL, P2_MODE_NORMAL, 0);
    packet2_t *vif = packet2_create(8, P2_TYPE_NORMAL, P2_MODE_CHAIN, 1);
    for (;;)
    {
        clear_screen(gif);
        draw_triangle(vif);
        graph_wait_vsync();
    }
}
